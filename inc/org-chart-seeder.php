/**
 * Seed or update Org Chart Nodes for a given subsite
 *
 * @param int $blog_id Subsite blog ID (default current blog)
 * @return array Status report
 */
function ha_seed_org_chart_nodes( $blog_id = null ) {
	if ( null !== $blog_id && is_multisite() ) {
		switch_to_blog( $blog_id );
	}

	$current_blog_id = get_current_blog_id();
	$locale = get_locale();
	$lang = 'en';
	if ( 2 === $current_blog_id || 0 === strpos( $locale, 'si' ) ) {
		$lang = 'si';
	} elseif ( 3 === $current_blog_id || 0 === strpos( $locale, 'ta' ) ) {
		$lang = 'ta';
	}

	$definitions = ha_get_org_chart_seed_definitions();

	// 1. Index existing posts by seed key to guarantee idempotency
	$existing_posts = get_posts( array(
		'post_type'      => 'ha_org_node',
		'post_status'    => 'any',
		'posts_per_page' => -1,
	) );

	$id_by_seed_key = array();
	foreach ( $existing_posts as $ep ) {
		$key = get_post_meta( $ep->ID, '_ha_org_seed_key', true );
		if ( ! empty( $key ) ) {
			$id_by_seed_key[ $key ] = $ep->ID;
		}
	}

	$created_count = 0;
	$updated_count = 0;
	$order_counter = array();

	// 2. Pass 1: Create or update all nodes with hierarchy and attributes
	foreach ( $definitions as $item ) {
		$key        = $item['seed_key'];
		$parent_key = $item['parent_seed_key'];

		// Calculate order per parent
		if ( ! isset( $order_counter[ $parent_key ] ) ) {
			$order_counter[ $parent_key ] = 0;
		}
		$order_counter[ $parent_key ]++;
		$menu_order = $order_counter[ $parent_key ];

		// Localized title
		$title = $item['title_en'];
		if ( 'si' === $lang && ! empty( $item['title_si'] ) ) {
			$title = $item['title_si'];
		} elseif ( 'ta' === $lang && ! empty( $item['title_ta'] ) ) {
			$title = $item['title_ta'];
		}

		$parent_post_id = ( ! empty( $parent_key ) && isset( $id_by_seed_key[ $parent_key ] ) ) ? (int) $id_by_seed_key[ $parent_key ] : 0;

		$post_data = array(
			'post_type'   => 'ha_org_node',
			'post_status' => 'publish',
			'post_title'  => $title,
			'post_parent' => $parent_post_id,
			'menu_order'  => $menu_order,
		);

		if ( isset( $id_by_seed_key[ $key ] ) ) {
			$post_id = $id_by_seed_key[ $key ];
			$post_data['ID'] = $post_id;
			wp_update_post( $post_data );
			$updated_count++;
		} else {
			$post_id = wp_insert_post( $post_data );
			if ( is_wp_error( $post_id ) || ! $post_id ) {
				continue;
			}
			update_post_meta( $post_id, '_ha_org_seed_key', $key );
			$id_by_seed_key[ $key ] = $post_id;
			$created_count++;
		}

		// Save Carbon Fields metadata
		if ( function_exists( 'carbon_set_post_meta' ) ) {
			carbon_set_post_meta( $post_id, 'org_card_style', $item['style'] );
			carbon_set_post_meta( $post_id, 'org_display_title', $item['display_title'] );
			carbon_set_post_meta( $post_id, 'org_acronym', $item['acronym'] );
			carbon_set_post_meta( $post_id, 'org_sub_label', $item['sub_label'] );
			carbon_set_post_meta( $post_id, 'org_division_key', $item['division'] );
			carbon_set_post_meta( $post_id, 'org_layout_preset', $item['preset'] );
			carbon_set_post_meta( $post_id, 'org_children_list_style', $item['children_list_style'] );
			carbon_set_post_meta( $post_id, 'org_children_mode', $item['children_mode'] );
			carbon_set_post_meta( $post_id, 'org_direct_branch', $item['direct_branch'] );
			carbon_set_post_meta( $post_id, 'org_stop_crossbar', $item['stop_crossbar'] );
			carbon_set_post_meta( $post_id, 'org_pair_group', $item['pair_group'] );
			carbon_set_post_meta( $post_id, 'org_cross_link_style', $item['cross_style'] );
		}
	}

	// 3. Pass 2: Connect cross-link associations
	foreach ( $definitions as $item ) {
		$key = $item['seed_key'];
		if ( ! isset( $id_by_seed_key[ $key ] ) ) {
			continue;
		}
		$post_id = $id_by_seed_key[ $key ];

		if ( ! empty( $item['cross_target'] ) && isset( $id_by_seed_key[ $item['cross_target'] ] ) ) {
			$target_id = $id_by_seed_key[ $item['cross_target'] ];
			carbon_set_post_meta( $post_id, 'org_cross_link_target', array(
				array(
					'type'      => 'post',
					'subtype'   => 'ha_org_node',
					'id'        => $target_id,
					'post_type' => 'ha_org_node',
				),
			) );

			if ( ! empty( $item['cross_anchor'] ) && isset( $id_by_seed_key[ $item['cross_anchor'] ] ) ) {
				$anchor_id = $id_by_seed_key[ $item['cross_anchor'] ];
				carbon_set_post_meta( $post_id, 'org_cross_link_anchor', array(
					array(
						'type'      => 'post',
						'subtype'   => 'ha_org_node',
						'id'        => $anchor_id,
						'post_type' => 'ha_org_node',
					),
				) );
			}
		}
	}

	// 4. Attach root node to Governance & Structure page
	$gov_pages = get_posts( array(
		'post_type'      => 'page',
		'meta_key'       => '_wp_page_template',
		'meta_value'     => 'page-templates/template-governance-structure.php',
		'post_status'    => 'publish',
		'posts_per_page' => 1,
	) );

	if ( ! empty( $gov_pages ) && isset( $id_by_seed_key['node_1'] ) ) {
		$gov_page_id = $gov_pages[0]->ID;
		$root_id     = $id_by_seed_key['node_1'];
		carbon_set_post_meta( $gov_page_id, 'gov_chart_root_node', array(
			array(
				'type'      => 'post',
				'subtype'   => 'ha_org_node',
				'id'        => $root_id,
				'post_type' => 'ha_org_node',
			),
		) );
	}

	if ( null !== $blog_id && is_multisite() ) {
		restore_current_blog();
	}

	return array(
		'blog_id' => $current_blog_id,
		'lang'    => $lang,
		'created' => $created_count,
		'updated' => $updated_count,
		'total'   => count( $id_by_seed_key ),
	);
}